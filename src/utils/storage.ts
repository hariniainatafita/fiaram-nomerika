// Phone numbers are ignored spaces/dashes/dots, the +261/261 prefix and the
// leading 0, so "034 11 222 33", "+261 34 11 222 33" and "341122233"
// are all the same number at sign-in.
function normalizePhone(value?: string): string {
  if (!value) return '';
  return value.replace(/\D/g, '');
}

function phoneMainDigits(value?: string): string {
  let digits = normalizePhone(value);
  if (digits.length >= 10 && digits.startsWith('261')) digits = digits.slice(3);
  if (digits.startsWith('0') && digits.length >= 9) digits = digits.slice(1);
  return digits;
}

function phonesMatch(stored?: string, typed?: string): boolean {
  const a = phoneMainDigits(stored);
  const b = phoneMainDigits(typed);
  if (!a || !b) return false;
  if (a === b) return true;
  if (b.length < 7) return false;
  return a.slice(-b.length) === b;
}

function getStoredItem<T>(key: string, defaultValue: T): T {
  try {
    const item = localStorage.getItem(key);
    return item ? JSON.parse(item) : defaultValue;
  } catch (e) {
    console.error(`Error loading key ${key}:`, e);
    return defaultValue;
  }
}

function setStoredItem<T>(key: string, value: T): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
    pushKey(key, value);
  } catch (e) {
    console.error(`Error saving key ${key}:`, e);
  }
}

/**
 * Image payloads (base64) can exceed the browser localStorage quota on
 * phones. Even then the picture must still reach every member, so the local
 * write is best-effort and the Supabase push always happens.
 */
function storeImageRow(key: string, dataUrl: string, label: string): boolean {
  let localOk = false;
  try {
    localStorage.setItem(key, JSON.stringify(dataUrl));
    localOk = true;
  } catch (e) {
    console.warn(`[image] cache local saturé pour ${label}, envoi direct au serveur:`, e);
  }
  pushKey(key, dataUrl);
  return localOk || (isSupabaseConfigured && Boolean(supabase));
}

